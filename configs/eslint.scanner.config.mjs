// Approximates the Obsidian community directory's source scan: the plugin's `recommended` config,
// the scanner's documented rule adjustments and its fixed ignore list, nothing of ours (no
// `.claude/**` ignore, no Vue rules). Source: eslint-plugin-obsidianmd docs/configuration.md
// § "Community plugin scanner configuration" (0.6.0). Informational only: `npm run lint:scanner`,
// not part of `npm run verify`. See docs/engineering/testing.md § "Scanner-equivalent lint".
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { defineConfig, globalIgnores } from "eslint/config";
import obsidianmd from "eslint-plugin-obsidianmd";
import tseslint from "typescript-eslint";

const ROOT = resolve(import.meta.dirname, "..");
const JS = "**/*.{js,cjs,mjs,jsx}";

const git = (/** @type {string[]} */ args) => {
  try {
    return execFileSync("git", args, { cwd: ROOT }).toString().split("\n").filter(Boolean);
  } catch {
    return [];
  }
};

/** The scanner checks a clone: what git does not track (build output, caches, worktrees) is not there. */
const untracked = () => git(["ls-files", "--others", "--directory"]);

/**
 * Bundled JavaScript outside the plugin's source, recognised by content as the scanner does: a
 * bundler banner in the first 500 bytes, or 500+ bytes whose first 500 hold fewer than two line
 * breaks. Every tsconfig here takes in `.ts`/`.vue`/`.mjs` only, so any `.js` outside `src/` is
 * outside the plugin's source.
 */
const bundled = () =>
  git(["ls-files", "--", "*.js", "*.jsx"])
    .filter((file) => !file.startsWith("src/"))
    .filter((file) => {
      const text = readFileSync(resolve(ROOT, file)).subarray(0, 500).toString();
      const banner = /GENERATED\/BUNDLED FILE|bundled by|generated by/i.test(text);
      return banner || (text.length >= 500 && text.split("\n").length - 1 < 2);
    });

