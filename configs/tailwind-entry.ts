import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The Tailwind entry of the plugin's stylesheet, written into `node_modules/.weg-manager/` at
 * build time as Nuxt UI writes its own `node_modules/.nuxt-ui/ui.css`. Tailwind's own at-rules
 * (`@source`, `@theme`) live here and nowhere in the checked-in CSS, which a plain CSS linter
 * (Obsidian's plugin review) reads as unknown at-rules. `src/styles/app.css` imports the file.
 */
const ROOT = fileURLToPath(new URL("../", import.meta.url));
export const TAILWIND_ENTRY = `${ROOT}node_modules/.weg-manager/tailwind.css`;

/**
 * The Nuxt UI components the plugin renders (and the ones they render inside). Nuxt UI scans
 * every component theme by default, which overruns the styles.css budget, so only these get
 * classes. Adding a Nuxt UI component means adding its theme name and its .vue file here.
 */
export const NUXT_UI_THEMES = [
  "app",
  "alert",
  "avatar",
  "button",
  "card",
  "form-field",
  "icon",
  "input",
  "link",
  "modal",
  "skeleton",
  "slideover",
  "textarea",
] as const;
export const NUXT_UI_COMPONENTS = [
  "App",
  "Alert",
  "Avatar",
  "Button",
  "Card",
  "FormField",
  "Icon",
  "Input",
  "Link",
  "LinkBase",
  "Modal",
  "Skeleton",
  "Slideover",
  "Textarea",
] as const;

/** A path of the repository as the entry file refers to it. */
const fromEntry = (path: string) => relative(dirname(TAILWIND_ENTRY), `${ROOT}${path}`);

/** The text of the Tailwind entry. */
export const tailwindEntry = (): string =>
  [
    "/* Generated by configs/tailwind-entry.ts; do not edit. */",
    // No Tailwind preflight: Obsidian owns the page; bridge.css carries the small reset.
    "@layer theme, base, components, utilities;",
    '@import "tailwindcss/theme.css" layer(theme) prefix(wm);',
    '@import "tailwindcss/utilities.css" layer(utilities) source(none);',
    `@source "${fromEntry("src/presentation")}";`,
    '@import "@nuxt/ui";',
    `@source not "${fromEntry("node_modules/.nuxt-ui/ui")}";`,
    `@source not "${fromEntry("node_modules/@nuxt/ui/dist/runtime/components")}";`,
    `@source "${fromEntry(`node_modules/.nuxt-ui/ui/{${NUXT_UI_THEMES.join(",")}}.ts`)}";`,
    `@source "${fromEntry(`node_modules/@nuxt/ui/dist/runtime/components/{${NUXT_UI_COMPONENTS.join(",")}}.vue`)}";`,
    // Unused palettes: Nuxt UI's static "old-neutral" and "neutral" for its runtime colors
    // plugin, a no-op here (scripts/no-head-plugins.mjs); colour roles come from bridge.css.
    "@theme {",
    "  --color-old-neutral-*: initial;",
    "  --color-neutral-*: initial;",
    "}",
    // Tailwind's text scale (--wm-text-*) follows Obsidian's UI font sizes; the rem fallbacks only
    // apply outside Obsidian (browser harness). xl and 2xl stay on Tailwind's scale.
    "@theme {",
    "  --text-xs: var(--font-ui-smaller, 0.75rem);",
    "  --text-sm: var(--font-ui-small, 0.875rem);",
    "  --text-base: var(--font-ui-medium, 1rem);",
    "  --text-lg: var(--font-ui-large, 1.125rem);",
    "}",
    "",
  ].join("\n");

/** Writes the entry when it is missing or differs, so a watching build is not restarted for nothing. */
export const writeTailwindEntry = (): void => {
  const text = tailwindEntry();
  let current: string | undefined;
  try {
    current = readFileSync(TAILWIND_ENTRY, "utf8");
  } catch {
    current = undefined;
  }
  if (current === text) return;
  mkdirSync(dirname(TAILWIND_ENTRY), { recursive: true });
  writeFileSync(TAILWIND_ENTRY, text);
};
